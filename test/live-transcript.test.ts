/**
 * Feature: spec/features/fspec-live-transcript.feature
 *
 * This test file validates the acceptance criteria defined in the feature file.
 * Scenarios in this test map directly to scenarios in the Gherkin feature.
 *
 * Live chunks are pushed as real Envelope::Event frames by the fake daemon;
 * replay pages are real get_transcript_page responses whose fragments carry
 * the daemon's serde-JSON StreamChunk entries.
 */
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { afterEach, describe, expect, it, vi } from "vitest";
import { parseStreamChunkJson } from "../server/transcript-json.js";
import * as wire from "../server/wire.js";
import { transcriptPages } from "./support/fake-daemon.js";
import {
  disposeHarnesses,
  harness,
  text,
  thinking,
  toolCall,
  toolProgress,
  toolResult,
} from "./support/provider-harness.js";

afterEach(disposeHarnesses);

/** Fixtures generated by Rust (bincode 1.3.3 + serde_json over codelet-rpc-types). */
function golden(name: string): string {
  return readFileSync(fileURLToPath(new URL(`./golden/${name}`, import.meta.url)), "utf8");
}
function vector(name: string): Uint8Array {
  const line = golden("golden-vectors.txt")
    .split("\n")
    .find((entry) => entry.startsWith(`${name} `))!;
  return new Uint8Array(Buffer.from(line.slice(name.length + 1).trim(), "hex"));
}

const DAEMON = "fspec-sess-42";

/** Opens paseo-1 and starts turn-1 so chunks belong to a Paseo turn. */
async function activeTurn() {
  const h = await harness();
  await h.open("paseo-1");
  await h.send(h.prompt("paseo-1", "go"));
  await h.waitFor("session.turn", (event) => event.state === "started");
  return h;
}

describe("Feature: Stream the live fspec transcript into Paseo's timeline", () => {
  describe("Scenario: Streaming text accumulates into one assistant item per contiguous segment", () => {
    it("accumulates deltas and opens a new segment after a tool call", async () => {
      // @step Given an open fspec session with an active Paseo turn
      const h = await activeTurn();
      // @step When the daemon streams Text "Hel", Text "lo", a ToolCall "call-1" for Bash with input {"command":"ls"}, then Text "Done"
      await h.stream(DAEMON, text("Hel"), text("lo"), toolCall("call-1", "Bash", { command: "ls" }), text("Done"));
      // @step Then the provider published assistant_message snapshots "Hel" then "Hello" under one item id
      const assistant = h.items("assistant_message");
      expect(assistant.map((item) => item.text)).toEqual(["Hel", "Hello", "Done"]);
      expect(assistant[0]!.id).toBe(assistant[1]!.id);
      // @step And it published tool_call "tool:call-1" with callId "call-1", status running, error null and shell detail command "ls"
      expect(h.items("tool_call")).toEqual([
        {
          type: "tool_call",
          id: "tool:call-1",
          callId: "call-1",
          name: "Bash",
          status: "running",
          error: null,
          detail: { type: "shell", command: "ls" },
        },
      ]);
      // @step And the text "Done" was published under a new assistant_message id
      expect(assistant[2]!.id).not.toBe(assistant[0]!.id);
      expect(new Set(h.ofType("timeline.item").map((event) => event.item.id)).size).toBe(3);
    });
  });

  describe("Scenario: Reasoning streams as its own reasoning item", () => {
    it("accumulates thinking into a reasoning item separate from text", async () => {
      // @step Given an open fspec session with an active Paseo turn
      const h = await activeTurn();
      // @step When the daemon streams Thinking "plan", Thinking "ning", then Text "ok"
      await h.stream(DAEMON, thinking("plan"), thinking("ning"), text("ok"));
      // @step Then the provider published reasoning snapshots "plan" then "planning" under one item id
      const reasoning = h.items("reasoning");
      expect(reasoning.map((item) => item.text)).toEqual(["plan", "planning"]);
      expect(reasoning[0]!.id).toBe(reasoning[1]!.id);
      // @step And the text "ok" was published as a separate assistant_message item
      const assistant = h.items("assistant_message");
      expect(assistant.map((item) => item.text)).toEqual(["ok"]);
      expect(assistant[0]!.id).not.toBe(reasoning[0]!.id);
    });
  });

  describe("Scenario: Tool progress and results update the same tool call item", () => {
    it("re-publishes the tool call with progress, then completes it", async () => {
      // @step Given an open fspec session with a running Bash tool call "call-1"
      const h = await activeTurn();
      await h.stream(DAEMON, toolCall("call-1", "Bash", { command: "ls" }));
      // @step When the daemon streams ToolProgress "a.txt\n" and then ToolResult "a.txt\nb.txt\n" for "call-1"
      await h.stream(DAEMON, toolProgress("call-1", "a.txt\n"), toolResult("call-1", "a.txt\nb.txt\n"));
      // @step Then the provider re-published "tool:call-1" running with shell output "a.txt\n" and then completed with output "a.txt\nb.txt\n"
      const snapshots = h.items("tool_call").filter((item) => item.id === "tool:call-1");
      expect(snapshots.map((item) => [item.status, item.detail])).toEqual([
        ["running", { type: "shell", command: "ls" }],
        ["running", { type: "shell", command: "ls", output: "a.txt\n" }],
        ["completed", { type: "shell", command: "ls", output: "a.txt\nb.txt\n" }],
      ]);
      // @step And a ToolCall named "Read" with input {"path":"x"} is published with unknown detail input {"path":"x"} and output null
      await h.stream(DAEMON, toolCall("call-2", "Read", { path: "x" }));
      expect(h.items("tool_call").at(-1)).toMatchObject({
        id: "tool:call-2",
        name: "Read",
        status: "running",
        detail: { type: "unknown", input: { path: "x" }, output: null },
      });
    });
  });

  describe("Scenario: A failing tool result marks the tool call failed", () => {
    it("publishes status failed with the result content as error", async () => {
      // @step Given an open fspec session with a running tool call "call-1"
      const h = await activeTurn();
      await h.stream(DAEMON, toolCall("call-1", "Write", { path: "/etc/x" }));
      // @step When the daemon streams a ToolResult for "call-1" with isError true and content "permission denied"
      await h.stream(DAEMON, toolResult("call-1", "permission denied", true));
      // @step Then the provider published "tool:call-1" with status failed and error "permission denied"
      expect(h.items("tool_call").at(-1)).toMatchObject({
        id: "tool:call-1",
        status: "failed",
        error: "permission denied",
        detail: { type: "unknown", input: { path: "/etc/x" }, output: "permission denied" },
      });
    });
  });

  describe("Scenario: Running tool calls are terminalized before the terminal turn event", () => {
    it("cancels the running tool before session.turn canceled", async () => {
      // @step Given an open fspec session whose active turn has a running tool call "call-2"
      const h = await activeTurn();
      await h.stream(DAEMON, toolCall("call-2", "Bash", { command: "sleep 100" }));
      // @step When the daemon streams Interrupted for the session
      await h.stream(DAEMON, { type: "interrupted", queuedInputs: [] });
      // @step Then the provider re-published "tool:call-2" with status canceled
      const canceledTool = h.ofType("timeline.item").find(
        (event) => event.item.type === "tool_call" && event.item.status === "canceled",
      );
      expect(canceledTool?.item).toMatchObject({ id: "tool:call-2", error: null });
      // @step And that tool_call event came before the session.turn canceled event
      const turn = await h.waitFor("session.turn", (event) => event.state === "canceled");
      expect(h.events.indexOf(canceledTool!)).toBeLessThan(h.events.indexOf(turn));
    });
  });

  describe("Scenario: Notifications and errors render as timeline rows", () => {
    it("maps notifications and errors, error before the failed turn", async () => {
      // @step Given an open fspec session with an active Paseo turn
      const h = await activeTurn();
      // @step When the daemon streams UserNotification "Rate limited" with severity Warning and then Error "provider exploded"
      await h.stream(
        DAEMON,
        { type: "userNotification", message: "Rate limited", severity: "warning" },
        { type: "error", error: "provider exploded" },
      );
      // @step Then the provider published a notification item with level warning and message "Rate limited"
      expect(h.items("notification")).toMatchObject([{ level: "warning", message: "Rate limited" }]);
      // @step And it published an error item with message "provider exploded" before the session.turn failed event
      const error = h.ofType("timeline.item").find((event) => event.item.type === "error")!;
      expect(error.item).toMatchObject({ message: "provider exploded" });
      const failed = await h.waitFor("session.turn", (event) => event.state === "failed");
      expect(h.events.indexOf(error)).toBeLessThan(h.events.indexOf(failed));
    });
  });

  describe("Scenario: Compaction renders as one row that goes from loading to completed", () => {
    it("publishes one compaction id loading then completed", async () => {
      // @step Given an open fspec session with an active Paseo turn
      const h = await activeTurn();
      // @step When the daemon streams CompactionProgressUpdate with progress and then CompactionComplete with original_tokens 90000
      await h.stream(
        DAEMON,
        { type: "compactionProgressUpdate", progress: { phase: "summarize", current: 1, total: 3 } },
        { type: "compactionProgressUpdate", progress: { phase: "summarize", current: 2, total: 3 } },
        {
          type: "compactionComplete",
          compactionResult: {
            originalTokens: 90000,
            compactedTokens: 30000,
            compressionRatio: 66.7,
            turnsSummarized: 4,
            turnsKept: 2,
          },
        },
      );
      // @step Then the provider published one compaction item with status loading and then the same id with status completed and preTokens 90000
      const compaction = h.items("compaction");
      expect(compaction.map((item) => item.status)).toEqual(["loading", "completed"]);
      expect(compaction[0]!.id).toBe(compaction[1]!.id);
      expect(compaction[1]).toMatchObject({ preTokens: 90000 });
    });
  });

  describe("Scenario: Token and context usage publish session.usage", () => {
    it("maps TokenUpdate and ContextFillUpdate", async () => {
      // @step Given an open fspec session whose active turn is "turn-1"
      const h = await activeTurn();
      // @step When the daemon streams TokenUpdate input 1200, output 300, cache_read 800 and ContextFillUpdate effective_tokens 50000 of context_window 200000
      await h.stream(
        DAEMON,
        {
          type: "tokenUpdate",
          tokens: {
            inputTokens: 1200,
            outputTokens: 300,
            cacheReadInputTokens: 800,
            cacheCreationInputTokens: null,
            tokensPerSecond: null,
            cumulativeBilledInput: null,
            cumulativeBilledOutput: null,
            reasoningTokens: null,
          },
        },
        {
          type: "contextFillUpdate",
          contextFill: { fillPercentage: 25, effectiveTokens: 50000, threshold: 0.9, contextWindow: 200000 },
        },
      );
      // @step Then the provider published session.usage with turnId "turn-1" and usage inputTokens 1200, outputTokens 300, cachedInputTokens 800
      const usage = h.ofType("session.usage");
      expect(usage[0]).toEqual({
        type: "session.usage",
        sessionId: "paseo-1",
        turnId: "turn-1",
        usage: { inputTokens: 1200, outputTokens: 300, cachedInputTokens: 800 },
      });
      // @step And it published session.usage with contextWindowUsedTokens 50000 and contextWindowMaxTokens 200000
      expect(usage[1]).toMatchObject({
        usage: { contextWindowUsedTokens: 50000, contextWindowMaxTokens: 200000 },
      });
    });
  });

  describe("Scenario: Activity from another client renders without inventing turns", () => {
    it("renders outside chunks and tags only Paseo echoes with clientMessageId", async () => {
      // @step Given an open fspec session with no active Paseo turn
      const h = await harness();
      await h.open("paseo-1");
      // @step When the daemon streams UserInput "hi from tui" and Text "hello" driven by another client
      await h.stream(DAEMON, { type: "userInput", text: "hi from tui" }, text("hello"));
      // @step Then the provider published user_message "hi from tui" with no clientMessageId and assistant_message "hello"
      expect(h.items("user_message")).toEqual([
        expect.objectContaining({ text: "hi from tui" }),
      ]);
      expect(h.items("user_message")[0]).not.toHaveProperty("clientMessageId");
      expect(h.items("assistant_message").map((item) => item.text)).toEqual(["hello"]);
      // @step And it emitted no session.turn event
      expect(h.ofType("session.turn")).toEqual([]);
      // @step And a Paseo prompt "fix it" with clientMessageId "client-1" followed by UserInput "fix it" publishes a user_message carrying clientMessageId "client-1"
      await h.send(h.prompt("paseo-1", "fix it", "client-1"));
      await vi.waitFor(() => expect(h.daemon.sent("sendInput")).toHaveLength(1));
      await h.stream(DAEMON, { type: "userInput", text: "fix it" });
      expect(h.items("user_message").at(-1)).toMatchObject({ text: "fix it", clientMessageId: "client-1" });
    });
  });

  describe("Scenario: Reopening with history replay publishes the daemon transcript before ready", () => {
    it("pages the transcript and replays it between config and ready", async () => {
      // @step Given a persisted fspec session "fspec-sess-42" whose daemon transcript holds UserInput "hi", Text "hello" and Done across several pages
      const h = await harness();
      h.daemon.handlers.getTranscriptPage = transcriptPages([
        JSON.stringify({ UserInput: { text: "hi" } }),
        JSON.stringify({ Text: { text: "hello", correlationId: null, observedCorrelationIds: null } }),
        JSON.stringify("Done"),
      ]);
      // @step When Paseo reopens it with that persistence and history "replay"
      const opened = await h.open("paseo-1", {}, { version: 1, data: { sessionId: DAEMON } }, "replay");
      // @step Then the provider paged get_transcript_page from no cursor to completion following snapshot_end and next_cursor
      const pages = h.daemon.sent("getTranscriptPage");
      expect(pages[0]).toEqual({
        method: "getTranscriptPage",
        sessionId: DAEMON,
        cursor: null,
        snapshotEnd: null,
        maxBytes: 65536,
      });
      expect(pages.length).toBeGreaterThan(3);
      expect(pages.slice(1).every((page) => page.snapshotEnd === 3 && page.cursor !== null)).toBe(true);
      expect(h.daemon.sent("createSessionChecked")).toEqual([]);
      // @step And it published user_message "hi" and assistant_message "hello" between session.config and session.ready with no session.turn or session.usage
      const types = opened.map((event) => event.type);
      expect(types[0]).toBe("session.opened");
      expect(types[1]).toBe("session.config");
      expect(types.at(-1)).toBe("session.ready");
      const replayed = h.ofType("timeline.item", opened);
      expect(replayed.map((event) => event.item)).toEqual([
        expect.objectContaining({ type: "user_message", text: "hi" }),
        expect.objectContaining({ type: "assistant_message", text: "hello" }),
      ]);
      expect(replayed[0]!.timestamp).toBe("2026-10-30T00:00:00Z");
      expect(types.filter((type) => type === "session.turn" || type === "session.usage")).toEqual([]);
      // @step And live chunks after ready are published under new ids that do not collide with the replayed ones
      await h.stream(DAEMON, text("again"));
      const live = h.items("assistant_message").at(-1)!;
      expect(live.text).toBe("again");
      expect(replayed.map((event) => event.item.id)).not.toContain(live.id);
    });

    it("matches the daemon's real transcript page and StreamChunk JSON encodings", () => {
      // @step Given a persisted fspec session "fspec-sess-42" whose daemon transcript holds UserInput "hi", Text "hello" and Done across several pages
      const page = vector("transcript_result_ok");
      // @step When Paseo reopens it with that persistence and history "replay"
      const frame = (method: wire.FspecMethodName, payload: Uint8Array) => {
        const header = new Uint8Array(16);
        const view = new DataView(header.buffer);
        view.setUint32(12, wire.FspecMethodIndex[method], true);
        return new Uint8Array([...header, ...payload]);
      };
      // @step Then the provider paged get_transcript_page from no cursor to completion following snapshot_end and next_cursor
      const decoded = wire.decodeResponseFrame(frame("getTranscriptPage", page));
      expect(decoded).toMatchObject({
        method: "getTranscriptPage",
        result: {
          ok: true,
          value: {
            generation: "g",
            snapshotEnd: 3,
            fragment: {
              sequence: 1,
              byteOffset: 0,
              totalBytes: 4,
              jsonFragment: '"Do"',
              original: { turnIndex: 2, messageId: "m", timestamp: "t", chunkIndex: 5 },
            },
            nextCursor: { generation: "g", sequence: 2, byteOffset: 0 },
            complete: false,
          },
        },
      });
      const reencoded = wire.encodeResponseFrame({
        requestId: 0,
        message: "getTranscriptPage",
        value: (decoded as { result: wire.TranscriptResult }).result,
      });
      expect(Buffer.from(reencoded.subarray(16)).toString("hex")).toBe(Buffer.from(page).toString("hex"));
      expect(wire.decodeResponseFrame(frame("getTranscriptPage", vector("transcript_result_err")))).toMatchObject({
        result: { ok: false, error: { kind: "sessionUnavailable", detail: "s" } },
      });
      expect(wire.decodeResponseFrame(frame("getTranscriptPage", vector("transcript_result_err_unit")))).toMatchObject({
        result: { ok: false, error: { kind: "invalidCursor" } },
      });
      const request = wire.encodeRequestFrame({
        id: 0,
        message: {
          method: "getTranscriptPage",
          sessionId: "s",
          cursor: { generation: "g", sequence: 2, byteOffset: 7 },
          snapshotEnd: 3,
          maxBytes: 65536,
        },
      });
      const args = Buffer.from(vector("transcript_args")).toString("hex");
      expect(Buffer.from(request).toString("hex").endsWith(args)).toBe(true);
      // @step And it published user_message "hi" and assistant_message "hello" between session.config and session.ready with no session.turn or session.usage
      const chunks = golden("stream-chunk-json.txt").trim().split("\n").map(parseStreamChunkJson);
      expect(chunks).toEqual([
        { type: "done" },
        { type: "text", text: "hi", correlationId: null, observedCorrelationIds: null },
        expect.objectContaining({ type: "toolCall", toolCall: { id: "c1", name: "Bash", input: '{"command":"ls"}' } }),
        expect.objectContaining({ type: "toolResult", toolResult: { toolCallId: "c1", content: "ok", isError: true } }),
        expect.objectContaining({
          type: "toolProgress",
          toolProgress: { toolCallId: "c1", toolName: "Bash", outputChunk: "x", isStderr: false },
        }),
        { type: "userNotification", message: "m", severity: "warning" },
        { type: "interruptedWithReason", queuedInputs: ["q"], reason: "loopDetector" },
        { type: "compactionProgressUpdate", progress: { phase: "p", current: 1, total: 2 } },
        { type: "userInput", text: "u" },
      ]);
      // @step And live chunks after ready are published under new ids that do not collide with the replayed ones
      expect(chunks).toHaveLength(9);
    });
  });

  describe("Scenario: A transcript error does not fail a replaying open", () => {
    it("publishes a warning notice and still becomes ready", async () => {
      // @step Given a persisted fspec session whose get_transcript_page fails with SessionUnavailable
      const h = await harness();
      h.daemon.handlers.getTranscriptPage = () => ({
        ok: false,
        error: { kind: "sessionUnavailable", detail: DAEMON },
      });
      // @step When Paseo reopens it with history "replay"
      const opened = await h.open("paseo-1", {}, { version: 1, data: { sessionId: DAEMON } }, "replay");
      // @step Then the provider published a warning session.notice naming the transcript error
      const notice = h.ofType("session.notice", opened)[0];
      expect(notice?.notice).toMatchObject({ severity: "warning" });
      expect(notice?.notice.description ?? notice?.notice.title).toContain(
        `transcript session is unavailable: ${DAEMON}`,
      );
      // @step And the open still completed with session.ready
      expect(opened.at(-1)).toMatchObject({ type: "session.ready", sessionId: "paseo-1" });
    });
  });
});
